## 1) فكرة النطاق: أنت مسؤول عمّا يخصك فقط

النظام يعمل بمبدأ **النطاق**: صلاحيتك مربوطة بمرحلة أو صف أو مادة أو مجموعة محددة، وليست عامة على كل المدرسة (إلا الناظر العام).

- **مشرف شعبة/طابق/مرحلة**: يرى وقد يعدّل ما ضمن نطاقه فقط (مثلاً: كل شعب مرحلته، أو كل شعب طابقه).
- **مشرف مبنى**: صلاحيته إدارية على المبنى (توزيع الطوابق والشعب)، وليست تعليمية.
- **لا يوجد مسؤول متكرر لنفس النطاق**: شعبة واحدة لها مشرف واحد فقط (يمكن أن يكون له مساعدون بلا حدود).
- **تصعد الصلاحية للأعلى تلقائياً**: إن لم يوجد مشرف مُعيَّن لمستوى معيّن (مثلاً لا مشرف لشعبة بعينها)، تنتقل مسؤوليتها لمشرف الطابق، فإن لم يوجد فمشرف المرحلة، وهكذا حتى الناظر العام. **وصاحب المستوى الأعلى يستطيع دائماً أن ينفّذ بدل الأدنى منه**، حتى لو كان معيَّناً.

