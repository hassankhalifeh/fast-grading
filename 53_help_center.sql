## 1) إنشاء حساب جديد (مدرسة تشتريك أو معلّم مستقل)

من «إنشاء حساب جديد»:

1. **نوع الحساب**: مدرسة (`school_enterprise`) أو فردي/معلّم مستقل (`solo_teacher`). الحقول تتكيّف مع اختيارك.
2. **الاسم**، **اسم المدير/المستخدم**، **البريد الإلكتروني** — يصله بريد دعوة لتعيين كلمة مروره بنفسه (**لا تُدخل أنت كلمة مرور لأحد**؛ ويحتاج هذا SMTP مُعَدّاً في Supabase وإلا لن يصل البريد).
3. **تنتهي الصلاحية في** — تاريخ اختياري؛ اتركه فارغاً لحساب بلا انتهاء.
4. **الحدود المسموحة**: عدد الصفوف، طلاب لكل صف، إجمالي الطلاب، الفروع/المباني، المراحل. القيم المقترحة: فردي 6 صفوف/30 طالباً للصف/150 إجمالاً/مبنى واحد/3 مراحل، ومدرسة 200/100/5000/10/20 — عدّلها حسب الباقة المتفَق عليها.
5. **تفعيل «مراسلات واتساب»** إن كانت الباقة تشملها (يمكن تفعيلها لاحقاً أيضاً).
6. اضغط **إنشاء الحساب وإرسال الدعوة**.

**هذا الزر له أثر حقيقي فوراً**: يرسل بريداً إلكترونياً حقيقياً، وينشئ حساباً وصلاحيات كاملة. لا تضغطه للتجربة.

## 2) تعديل حساب قائم

من جدول الحسابات، زر **«تعديل الحدود»** أمام أي حساب يفتح صفاً لتعديل: الحدود الخمسة، تاريخ الانتهاء، **الحالة** (نشط / موقوف يدوياً — للتعليق الفوري بلا حذف)، اسم الباقة، وملاحظة داخلية لك. الحفظ يُطبَّق في قاعدة البيانات فوراً على كل عمليات الحساب اللاحقة.

عمود «الاشتراك» في الجدول يلوّن الحالة: أخضر (نشط)، أصفر (ينتهي خلال 14 يوماً)، أحمر (منتهي أو موقوف) — مع عرض الاستعمال الحالي مقابل الحد (مثلاً «صفوف 6/200»).

**ماذا يحدث عند الانتهاء أو الإيقاف؟** يُمنع إضافة صفوف/طلاب/فروع/مراحل جديدة، وإدخال علامات جديدة، وإرسال مراسلات واتساب جديدة — فرضاً في قاعدة البيانات نفسها. **لا يُمنع** الاطلاع على البيانات والتقارير الموجودة، حتى تحتفظ المدرسة بإمكانية التصدير عند انتهاء تعاملها معك.

## 3) تفعيل/إيقاف الإضافات (مثل واتساب)

خانة الاختيار في عمود الإضافة بجدول الحسابات تفعّلها أو توقفها فوراً. **تفعيلك هذا يعني فقط الإذن**؛ المدرسة نفسها تُدخل بيانات رقمها وحسابها لدى Meta من شاشتها («إعدادات واتساب»)، وتستطيع هي إيقاف الخدمة أو تشغيلها من جهتها متى شاءت طالما الإذن قائم.

## 4) مراجعة مخالفات المحتوى (كل المدارس)

قسم «مخالفات المحتوى» يعرض كل رسالة حُجبت في أي مدرسة لاحتوائها ألفاظاً غير لائقة، مع النص والمستخدم والمدرسة. راجعها وأكّد أو ألغِ (إنذار كاذب) مع ملاحظة.

## 5) قاموس الألفاظ العام

القائمة الأساسية للألفاظ المحجوبة (جنسية/نابية/إهانة/تهديد) تنطبق على كل المدارس. راجعها ووسّعها بين حين وآخر — **كُتبت ابتدائياً بمعرفتي وتحتاج مراجعة من شخص عربي ملمّ باللهجات المحلية** قبل التوسّع في البيع. لكل مدرسة أيضاً قاموسها الخاص من شاشتها.

## 5-ب) الخلفية الافتراضية للمنصة

