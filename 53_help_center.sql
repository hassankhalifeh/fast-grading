## ١) مالك المنصة

يشغّل المنصة ويبيعها لمدارس ومعلمين مستقلين، من `/platform` (لا يظهر إلا لمن أُدرج في `platform_admins`). ينشئ الحسابات، يحدد نوعها وحدودها وتاريخ انتهائها، يفعّل الإضافات (مثل واتساب)، ويراجع مخالفات المحتوى عبر كل المدارس.

**التفصيل الكامل:** [دليل مالك المنصة](help:platform-owner-guide)

## ٢) الحساب ونوعه

كل مدرسة أو معلّم مستقل هو **حساب واحد** (`account`) بنوعين ممكنين:

| النوع | المفتاح | يملك تلقائياً |
|---|---|---|
| معلّم مستقل | `solo_teacher` | **كل** الصلاحيات الـ23 تلقائياً، بلا حاجة لدعوة أحد |
| مدرسة | `school_enterprise` | يُنشأ أول مستخدم بدور **الناظر العام** (`school_admin`)، ويدعو هو الباقي |

لكل حساب **حدود اشتراك** يضبطها مالك المنصة فقط: عدد الصفوف، الطلاب لكل صف، إجمالي الطلاب، الفروع/المباني، المراحل، وتاريخ انتهاء اختياري. عند بلوغ الحد أو انتهاء الصلاحية تُمنع العمليات الجديدة (إضافة صفوف/طلاب، علامات جديدة، مراسلات) — فرضاً في قاعدة البيانات نفسها — مع بقاء كل البيانات والتقارير القائمة قابلة للعرض والتصدير.

## ٣) إدارة الحساب — الناظر العام / المعلّم المستقل

من يملك كل الصلاحيات الإدارية على حسابه بالكامل: تهيئة المدرسة أول مرة (14 خطوة بالترتيب)، الإدارة المستمرة (نافذة العلامات، قفل الامتحانات، التكميلي)، مركز التقارير، ومراسلات واتساب إن فُعِّلت.

**التفصيل الكامل:** [دليل الناظر العام / مدير المدرسة](help:school-admin-guide)

## ٤) الأدوار التنفيذية الثابتة

أدوار جاهزة يختارها الناظر العام عند دعوة كل مستخدم، ولكل منها مجموعة صلاحيات افتراضية (قابلة للتعديل لاحقاً من شاشة الصلاحيات):

- **مساعد الناظر** (`assistant_admin`) — يدخل العلامات، يعدّل علامات غيره، يرى كل العلامات، ويدير الرستر (الصفوف/الطلاب).
- **أستاذ مادة** (`subject_teacher`) — يدخل علامات موادّه وشعبه المُسنَدة إليه فقط. دليله الكامل: [دليل الأستاذ](help:teacher-guide).
- **دور مخصص** (`custom_role`) — يبدأ بصلاحية الاطلاع على التقارير فقط، ويُبنى بالكامل يدوياً من شاشة الصلاحيات لأي مزيج تحتاجه مدرستك (مثل محاسب يرى التقارير فقط، أو مُدخِل بيانات يستورد الملفات دون شيء آخر).

## ٥) المشرفون بالنطاق + مبدأ تصاعد الصلاحية

أي مستخدم (عادة مساعد ناظر أو دور مخصص) يمكن أن يُعطى إشرافاً على **نطاق محدد** بدل المدرسة كلها: شعبة، طابق، مرحلة، أو مبنى (إداري فقط، بلا شأن تعليمي). القواعد الثابتة:

- لا يوجد مسؤول متكرر لنفس النطاق (شعبة واحدة = مشرف واحد، يمكن أن يملك مساعدين بلا حدود).
- **تصاعد تلقائي**: إن لم يوجد مشرف لمستوى معيّن، تنتقل المسؤولية للمستوى الأعلى (شعبة → طابق → مرحلة → الناظر العام)، وصاحب المستوى الأعلى يقدر دائماً أن ينفّذ بدل الأدنى حتى لو كان معيَّناً.
- أستاذ ثانٍ لنفس المادة والشعبة يحتاج موافقة الناظر العام صراحة.

**التفصيل الكامل:** [دليل المشرفين](help:supervisor-guide)

## ٦) أين تُمنح الصلاحيات فعلياً في البرنامج

من شاشة **الصلاحيات** (تحتاج `users.manage`)، جزءان:

1. **المصفوفة العامة**: قائمة كل مستخدم × كل صلاحية من الـ23 أدناه، تفعيلاً أو إلغاءً مباشراً — هذه صلاحية **عامة على كل المدرسة** إن فُعِّلت.
2. **النطاقات** (`ScopesPanel`): تُنشئ **مجموعة نطاق** (مراحل + صفوف + مواد معاً — التقاطع هو ما يغطيه، مثلاً «رياضيات بالمرحلة المتوسطة»)، ثم تربط مستخدماً بمجموعة وصلاحية معيّنة؛ هذه الصلاحية تنطبق **داخل المجموعة فقط**. هذا ما يبني الإشراف على شعبة/طابق/مرحلة فعلياً.

