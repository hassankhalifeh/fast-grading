## 3) إدخال العلامات

1. من «إدخال العلامات» اختر **الامتحان** (شعبة + مادة + امتحان). لا تظهر لك إلا الامتحانات في الصفوف/المواد المُسنَدة إليك.
2. يظهر جدول بأسماء طلاب الشعبة. إن كان الامتحان مُدخلاً جزئياً من قبل تظهر العلامات السابقة معبّأة.
3. اكتب علامة كل طالب. إن كان الامتحان متعدد المكوّنات (مثلاً تحريري + شفهي) يظهر عمود لكل مكوّن.
4. اضغط **حفظ العلامات**.

