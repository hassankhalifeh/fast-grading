2. اضغط الزر وقل: «اسم الطالب» ثم «العلامة» — مثال: «محمد أحمد خمسة وثمانين».
3. يظهر جدول مسوّدة بالأسماء والعلامات التي فهمها النظام. **راجعها جيداً**: إن كان الاسم ملتبساً تظهر أسماء مقترحة، اختر الصحيح.
