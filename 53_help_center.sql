1. **إعدادات واتساب**: شغّل الخدمة، وأدخل بيانات رقم واتساب مدرستك (من حساب Meta الخاص بكم) واحفظ. بلا هذه البيانات يعمل الإرسال بفتح واتساب يدوياً برسالة جاهزة.
2. **قوالب الرسائل**: اكتب صياغة مدرستك لكل نوع مراسلة (نتيجة امتحان، تنبيه دون حد النجاح، نتيجة فصل، دعوة تكميلي، نتيجة ترفيع). النظام يرفض تلقائياً أي صياغة فيها **ألفاظ خادشة للحياء** ويسجّلها مخالفة (انظر أدناه).
3. **مراسلات أولياء الأمور**: اختر نوع المراسلة ومصدرها (امتحان/صف/دور) ← تُنشأ **مسودة** يُحدَّد فيها الجميع افتراضياً ← راجعها وألغِ من لا تريد وعدّل ما يلزم استثنائياً ← **اعتمدها** (قد تشترط مدرستك أن يعتمدها شخص غيرك) ← أرسِل.
4. **سجل محادثات واتساب**: أرشيف دائم لكل رسالة صادرة وواردة، حتى لو غيّرتم رقم المدرسة لاحقاً.
5. **مراجعة المخالفات**: أي رسالة حُجبت لاحتوائها ألفاظاً غير لائقة تظهر هنا مع اسم من كتبها؛ راجعها وأكّدها أو ألغِها (إنذار كاذب)، ويمكنك إضافة كلمات إلى قاموس مدرستك الخاص.

