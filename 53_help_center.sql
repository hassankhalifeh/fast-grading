## 1) تسجيل الدخول

افتح رابط المدرسة الذي أرسلته لك الإدارة (مثلاً `fast-grading.vercel.app`)، وادخل ببريدك وكلمة المرور التي عيّنتها من رسالة الدعوة. إن نسيت كلمة المرور اضغط «نسيت كلمة المرور؟» في صفحة الدخول.

## 2) ما تراه في القائمة

أول ما يفتح لك صفحة **الرئيسية** (أرقام سريعة واختصارات). تقدر تجعل أي صفحة أخرى — مثل «إدخال العلامات» — صفحتك الافتراضية بزر «اجعلها صفحتي الافتراضية» أعلى الصفحة، فتفتح مباشرة عند دخولك. وفي آخر القائمة **المساعدة** تجد هذا الدليل وغيره، وزر «؟» أعلى كل شاشة يفتح الجزء المتعلق بها.


