## خطوات تنفيذية موحَّدة (من الصفر حتى التشغيل اليومي)

1. **مالك المنصة** ينشئ الحساب ويحدد نوعه وحدوده (§١).
2. **الناظر العام** يسجّل دخوله أول مرة ويتبع الـ14 خطوة في «معلومات المدرسة → قائمة تهيئة مدرسة جديدة» (§٣).
3. الناظر العام **يدعو المستخدمين**: أساتذة بدور `subject_teacher`، مساعدين بدور `assistant_admin`، أو أدواراً مخصصة.
4. من **الصلاحيات**، يحدّد لكل مستخدم ما يلزمه بالضبط ويُنشئ النطاقات للمشرفين (§٦).
5. يفتح **نافذة العلامات**، والأساتذة يدخلون العلامات ضمن ما أُسند إليهم.
6. **مركز التقارير** للمتابعة اليومية (اكتمال العلامات، تغطية التدريس، النجاح/الرسوب).
7. آخر السنة: **الامتحان التكميلي** للطلاب الضعفاء، ثم الشهادات النهائية.

