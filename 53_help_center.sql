## المرحلة 1 — تهيئة المدرسة أول مرة

اتبع هذا الترتيب بالضبط؛ كل خطوة تعتمد على ما قبلها.

1. **معلومات المدرسة**: الاسم، المدير، الهاتف، العنوان، **رمز الدولة** لأرقام أولياء الأمور، وتذييل الشهادة (تظهر على الشهادات والرسائل). ومن هنا أيضاً ترفع **خلفية الحساب**: صورة تظهر خلف كل صفحات لوحة التحكم لمدرستك؛ إن لم ترفع واحدة تُستعمل خلفية المنصة الافتراضية، ويمكنك إزالتها في أي وقت.
2. **المواد**: أضف كل مادة تُدرَّس.
3. **المراحل**: المراحل الدراسية (روضة، ابتدائي، متوسط...) بترتيب عرضها.
4. **قوالب الاختبارات**: بنية الامتحان (مثلاً تحريري فقط، أو تحريري + شفهي) — كل قالب له مكوّناته الخاصة.
5. **الهيكل الأكاديمي**: السنة الدراسية → الفصول → بنود التقييم (مثل: سعي 1، سعي 2، امتحان الفصل) وأوزانها الافتراضية.
6. **سياسة العلامات**: حد النجاح (بالنسبة المئوية) وصيغة حساب المعدل.
7. **المعدلات والأوزان**: عدّل الأوزان الافتراضية إن احتجت استثناء لمرحلة أو صف أو مادة معيّنة (الأكثر تحديداً يفوز دائماً).
8. **الصفوف**: أنشئ شعب المدرسة (الصف + الشعبة + المرحلة).
9. **الطلاب**: أضفهم يدوياً واحداً واحداً (مع تسجيلهم في شعبهم وهاتف ولي الأمر)، أو من **الاستيراد الجماعي**: لكل جدول (المواد، المراحل، الطلاب، الصفوف، المعلمون) زر «تنزيل نموذج Excel» جاهز تملؤه وترفعه (يقبل CSV أيضاً)، وتبويب **«ملف Excel شامل»** يستورد المواد والمراحل والصفوف والطلاب والمعلمين من ملف واحد متعدد الأوراق. استيراد الطلاب يعرض تعارضات الأسماء المتشابهة للمراجعة قبل الاعتماد.
10. **الهيكل التنظيمي** (اختياري): أنشئ مبانيَ وطوابقَ إن كانت مدرستك متعددة المباني، ووزّع الشعب عليها.
11. **المستخدمون**: ادعُ الأساتذة والمشرفين ببريدهم الإلكتروني ودورهم (تصلهم دعوة لتعيين كلمة مرورهم).
12. **إسناد الأساتذة**: اربط كل أستاذ بصفه/مادته. أستاذ ثانٍ لنفس المادة والشعبة يحتاج موافقتك الصريحة.
13. **الصلاحيات**: امنح كل مستخدم ما يلزمه فقط (الاطلاع على شرح كل صلاحية بجانبها)، وحدّد نطاق المشرفين (شعبة/طابق/مرحلة/مبنى) من نفس الشاشة.
14. **الامتحانات**: أنشئ امتحاناً لكل شعبة+مادة، مرتبطاً ببند تقييم من الهيكل الأكاديمي.

بعد هذا، الأساتذة يدخلون العلامات، والمعدلات والتقارير تُحسب تلقائياً.

## الصفحة الرئيسية والمساعدة

- **الرئيسية** هي أول ما يفتح: أرقام سريعة (الطلاب، الصفوف، الامتحانات المفتوحة للعلامات) واختصارات. ولكل مستخدم أن يجعل أي صفحة أخرى صفحته الافتراضية بزر «اجعلها صفحتي الافتراضية» أعلى تلك الصفحة.
- **المساعدة** (آخر القائمة الجانبية): كل الأدلة المناسبة لدورك، مع بحث، وزر «؟» أعلى كل شاشة يفتح الجزء المتعلق بها.

## المرحلة 2 — الإدارة المستمرة خلال السنة

- **نافذة العلامات**: في حسابات المدارس، لا يدخل الأساتذة علامات إلا إذا فتحتَ النافذة (زر في شاشة إدخال العلامات إن ملكت `window.toggle`). أقفلها بعد انتهاء فترة الإدخال لمنع تعديلات لاحقة غير مرغوبة.
- **قفل الامتحانات**: اعتمد الامتحان نهائياً (قفل) بعد التأكد من اكتمال علاماته؛ يمكن فتحه لاحقاً إن احتجت تصحيحاً استثنائياً.
- **حل تعارضات العلامات**: عند إدخال أكثر من علامة لنفس الطالب، يقرر المُدخِل (أو أنت) أيهما يبقى.
- **الامتحان التكميلي** (آخر السنة): حدّد المواد المتاحة للتكميلي، راجع قائمة الطلاب المستحقين (يقترحها النظام تلقائياً من دون حد النجاح)، أنشئ امتحاناً لكل شعبة/مادة، وبعد إدخال العلامات تُحسب النتيجة النهائية والترفيع تلقائياً حسب سياسة الدور (استبدال / الأعلى / سقف عند حد النجاح) دون أن تمس معدلات الفصول.

## المرحلة 3 — مركز التقارير

شاشة واحدة بست فئات:
1. **العلامات والمعدلات**: بطاقة العلامات، معدلات الصف، ملخص الصفوف والمدرسة، الأوزان المطبَّقة، والشهادة الفردية.
2. **الشهادات**: طباعة شهادة كل طلاب صف دفعة واحدة.
3. **النتائج والتحصيل**: النجاح والرسوب لكل مادة، ونتائج التكميلي والترفيع لدور كامل.
4. **متابعة العمل**: امتحانات ناقصة العلامات، تغطية التدريس (أي صف/مادة بلا أستاذ)، نشاط إدخال العلامات لكل مستخدم، سجل الاستيراد الجماعي.
5. **مراسلات واتساب** (إن فُعّلت — انظر أدناه): ملخص الرسائل.
6. **إدارية** (تحتاج صلاحية إدارة إضافات/مستخدمين): المستخدمون وصلاحياتهم، وسجل التدقيق (من عدّل ماذا ومتى).

كل تقرير قابل للتصدير CSV.

## المرحلة 4 — مراسلات أولياء الأمور عبر واتساب (إضافة اختيارية)

